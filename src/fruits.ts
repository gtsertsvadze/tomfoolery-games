// Lowercase, trim, strip spaces/hyphens/apostrophes for lookup.
export function normalize(raw: string): string {
  return raw
    .normalize("NFKC")
    .toLowerCase()
    .trim()
    .replace(/[\s\-_'’.]/g, "");
}

function stripPlural(word: string): string | null {
  if (word.length > 4 && word.endsWith("ies")) return word.slice(0, -3) + "y";
  if (word.length > 4 && word.endsWith("oes")) return word.slice(0, -2);
  if (
    word.length > 5 &&
    (word.endsWith("ches") ||
      word.endsWith("shes") ||
      word.endsWith("xes") ||
      word.endsWith("sses") ||
      word.endsWith("zzes"))
  )
    return word.slice(0, -2);
  if (word.length > 3 && word.endsWith("s") && !word.endsWith("ss"))
    return word.slice(0, -1);
  return null;
}

// Levenshtein distance capped at max+1 (early exit).
function cappedDistance(a: string, b: string, max: number): number {
  if (Math.abs(a.length - b.length) > max) return max + 1;
  let prev = new Array<number>(b.length + 1);
  for (let j = 0; j <= b.length; j++) prev[j] = j;
  for (let i = 1; i <= a.length; i++) {
    let cur0 = i;
    let rowMin = cur0;
    let prevDiag = prev[0];
    prev[0] = i;
    for (let j = 1; j <= b.length; j++) {
      const temp = prev[j];
      const cost = a.charCodeAt(i - 1) === b.charCodeAt(j - 1) ? 0 : 1;
      const v = Math.min(prev[j] + 1, cur0 + 1, prevDiag + cost);
      prevDiag = temp;
      prev[j - 1] = cur0;
      cur0 = v;
      if (v < rowMin) rowMin = v;
    }
    prev[b.length] = cur0;
    if (rowMin > max) return max + 1;
  }
  return prev[b.length];
}

