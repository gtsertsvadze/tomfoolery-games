// Returns the canonical fruit name, or null when unknown.
export function matchFruit(raw: string): string | null {
  const key = normalize(raw);
  if (!key) return null;
  const direct = fruitSet.get(key) ?? aliasMap.get(key);
  if (direct) return direct;
  const singular = stripPlural(key);
  if (singular) {
    const hit = fruitSet.get(singular) ?? aliasMap.get(singular);
    if (hit) return hit;
  }
  if (NOT_FRUITS.has(key)) return null;
  if (singular && NOT_FRUITS.has(singular)) return null;
  // Typo matching: short inputs are almost always jokes, not typos, and
  // real typos keep the first letter (kivi -> kiwi).
  if (key.length < 4) return null;
  let best: string | null = null;
  let bestDist = 3;
  let bestPrimary = false;
  for (const c of typoCandidates) {
    if (c.key[0] !== key[0]) continue;
    const d = cappedDistance(key, c.key, 2);
    if (
      d < bestDist ||
      (d === bestDist && c.primary && !bestPrimary && best !== null)
    ) {
      if (d > 2) continue;
      best = c.canonical;
      bestDist = d;
      bestPrimary = c.primary;
      if (d === 0) break;
    }
  }
  return bestDist <= 2 ? best : null;
}
